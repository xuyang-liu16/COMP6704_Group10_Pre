"""Refresh the Beamer result tables from the existing experiment snapshots."""
from pathlib import Path
import hashlib
import json
import math


HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
METHODS = {"gd": "GD", "nesterov": "Nesterov", "fista": "FISTA", "admm": "ADMM"}


def scientific(value):
    mantissa, exponent = f"{value:.2e}".split("e")
    return rf"${mantissa}\times10^{{{int(exponent)}}}$"


def main():
    tables = {}
    for dataset, folder, shape in [
        ("synthetic", ROOT / "results", (1500, 500, 51)),
        ("breast_cancer", ROOT / "results/breast_cancer", (426, 143, 31)),
    ]:
        source = folder / "summary.json"
        raw = source.read_bytes()
        summary = json.loads(raw)
        lines = [
            f"% Generated by refresh_tables.py from {source.relative_to(ROOT)}",
            f"% SHA-256: {hashlib.sha256(raw).hexdigest()}",
            r"\begin{center}",
            r"\small\setlength{\tabcolsep}{5pt}\renewcommand{\arraystretch}{1.3}",
            r"\begin{tabular}{lrrrrr}",
            r"\toprule",
            r"Method & Final $F$ & $\|\nabla F\|_2$ & Updates & Wall, ms & Test acc. \\",
            r"\midrule",
        ]
        for key, label in METHODS.items():
            h = summary[key]
            cfg = h["config"]
            expected = {
                "dataset": dataset, "seed": 0, "lam": 0.01,
                "max_iter": 400, "tol": 1e-6,
                "n_train": shape[0], "n_test": shape[1], "n_features": shape[2],
            }
            if cfg != expected or not h["ok"]:
                raise ValueError(f"{dataset}/{key}: unexpected configuration or failed run")
            for metric in ("final_obj", "final_grad_norm", "wall_s", "test_acc"):
                if not math.isfinite(h[metric]):
                    raise ValueError(f"{dataset}/{key}: nonfinite {metric}")
            if h["gradient_converged"] != (h["final_grad_norm"] <= cfg["tol"]):
                raise ValueError(f"{dataset}/{key}: inconsistent convergence flag")
            # The slide conclusions depend on these snapshot-specific checks.
            if h["gradient_converged"] != (dataset == "synthetic"):
                raise ValueError(f"{dataset}/{key}: convergence changed; revise the slide narrative")
            if dataset == "breast_cancer" and h["n_iter"] != 400:
                raise ValueError(f"{dataset}/{key}: budget changed; revise the slide narrative")
            if dataset == "synthetic" and key == "admm" and not h["converged"]:
                raise ValueError("Synthetic ADMM did not satisfy its own stopping rule")
            if dataset == "synthetic":
                expected_iterations = {"gd": 136, "nesterov": 138, "fista": 138, "admm": 195}
                if h["n_iter"] != expected_iterations[key] or f"{h['final_obj']:.10f}" != "0.4932140405":
                    raise ValueError(f"{dataset}/{key}: endpoint changed; revise the slide narrative")
            expected_accuracy = "73.80" if dataset == "synthetic" else "96.50"
            if f"{100 * h['test_acc']:.2f}" != expected_accuracy:
                raise ValueError(f"{dataset}/{key}: accuracy changed; revise the slide narrative")
            lines.append(
                f"{label} & {h['final_obj']:.10f} & {scientific(h['final_grad_norm'])}"
                f" & {h['n_iter']} & {1000 * h['wall_s']:.2f}"
                f" & {100 * h['test_acc']:.2f}\\% " + r"\\"
            )
        lines.extend([r"\bottomrule", r"\end{tabular}", r"\end{center}", ""])
        tables[dataset] = "\n".join(lines)

    output = HERE / "tables"
    output.mkdir(exist_ok=True)
    for dataset, text in tables.items():
        path = output / f"{dataset}.tex"
        path.write_text(text, encoding="utf-8")
        print(f"Updated {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
